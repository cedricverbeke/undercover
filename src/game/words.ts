export const WORD_DATA: Record<LangCode, WordCategory[]> = {
  fr,
  en,
  es,
  de,
  it,
  pt,
};

export const FREE_PAIR_COUNT = 30;

export function getFreeWordPairs(lang: LangCode): typeof fr[number]['words'] {
  const categories = WORD_DATA[lang];
  const result: WordPair[] = [];
  for (const cat of categories) {
    for (const pair of cat.words) {
      if (result.length >= FREE_PAIR_COUNT) break;
      result.push(pair);
    }
    if (result.length >= FREE_PAIR_COUNT) break;
  }
  return result.slice(0, FREE_PAIR_COUNT);
}

export function getCategoryWords(
  lang: LangCode,
  categoryId: string,
  isPremium: boolean
): WordPair[] {
  const categories = WORD_DATA[lang];
  const cat = categories.find((c) => c.id === categoryId);
  if (!cat) return [];
  if (isPremium) return cat.words;
  const free = getFreeWordPairs(lang);
  return cat.words.filter((pair) =>
    free.some(
      (f) =>
        f.civil === pair.civil &&
        f.undercover === pair.undercover &&
        f.theme === pair.theme
    )
  );
}

export function buildPool(
  lang: LangCode,
  categoryIds: string[],
  isPremium: boolean
): WordPair[] {
  const pool: WordPair[] = [];
  for (const catId of categoryIds) {
    pool.push(...getCategoryWords(lang, catId, isPremium));
  }
  return pool;
}
